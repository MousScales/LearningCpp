#include <iostream>

int main()
{
    std::cout << "\t";
    // adds a tab space
    std::cout << "\b";
    // deletes a character
    std::cout << "\n";
    // goes to next line
    std::cout << "\v";
    // vertical tab
    std::cout << "\0";
    // null terminating charcter used in c to mark the end of the string
    std::cout << "yo \"dad\"";
    // lets your print or output ""s can also do the same for single quotes
    std::cout << "\\";
    // lets you print out backslashes 
}